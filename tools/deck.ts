// Build-time slide compilation (marp-core, a superset of the Marpit dialect):
// shared by whole-deck posts (frontmatter deck: true) and ```marp fences in
// ordinary bodies. For site extensions unsupported by deck content see the
// "dialect boundary" note at the end of this file; already bridged: mermaid
// (placeholder containers + the site renderer), math KaTeX, callouts,
// ==mark==, emoji, task lists, definition lists, sequence/flow (translated to
// mermaid). Output is static <section>s + theme CSS with zero Marp code on
// the client (the player lives in features/deck).
//
// Output conventions (three-way contract with src/features/deck/DeckViewer.tsx
// and pageData.ts):
//   - section ids are always stripped and replaced with data-slide (multiple
//     decks on one page would trip the duplicate-id audit), and headings are
//     demoted one level overall (h1 is ceded to the post title; heading-order
//     audit);
//   - code blocks are re-highlighted with the site's shiki dual themes, and
//     site-local images get intrinsic dimensions (unsized-images audit);
//     presenter notes (HTML comments) are injected into each page's
//     .deck-notes;
//   - the embed form's CSS strips @page (otherwise it hijacks the paper size
//     of the printed article).

import { readFileSync } from "node:fs";
import { join } from "node:path";
import { Marp } from "@marp-team/marp-core";
import { mark } from "@mdit/plugin-mark";
import { tasklist } from "@mdit/plugin-tasklist";
import { imageSize } from "image-size";
import markdownItDeflist from "markdown-it-deflist";
import { deckCallouts } from "./deckCallouts";
import deckThemeCss from "./deckTheme.css?raw";
import { translateFlowToMermaid, translateSequenceToMermaid } from "./diagrams";
import { decodeEntities, escapeAttr, escapeHtml } from "./html.ts";
import { highlightCode } from "./shiki.ts";

export interface DeckResult {
  /** Per-slide section HTML (with data-slide numbering, no container) */
  slides: string[];
  /** Full styles generated by marpit (theme scoped to div.marpit > section + normalization) */
  css: string;
  count: number;
}

/** Site seam (DESIGN.md §5.2 family contract): one compilation pipeline runs
 *  on two sites — ZJBlog at build time (trusted author, shiki, local image
 *  dimensions) and ZJSearch at runtime (model content, no shiki, no local
 *  file system). Defaults = blog behavior; call sites need zero changes. */
export interface DeckCompileOptions {
  /** Raw HTML in source: true = trusted-author pass-through (blog); false =
   *  escaped into visible text (model content — parsing of directive comments
   *  and presenter notes is unaffected, confirmed by testing) */
  html?: boolean;
  /** Code fence highlighter (takes decoded code, returns HTML); by default
   *  keeps markdown-it's default form (escaped code block) — the blog passes
   *  the site's shiki dual-theme pass */
  highlight?: (lang: string, code: string) => string;
  /** Inject intrinsic dimensions for site-local images (src starting with "/")
   *  (the blog's unsized-images audit); the runtime renderer has no local
   *  file system, so it stays off there */
  imageSizes?: boolean;
  /** Demote headings one level overall (h1 is ceded to the post title; the
   *  blog's heading-order audit); standalone decks (without post-title
   *  context) keep the author's levels */
  demoteHeadings?: boolean;
}

// The kernel is marp-core (math KaTeX and emoji shortcodes are taken over by
// the kernel, replacing the hand-wired @mdit/plugin-katex / plugin-emoji).
// The constructor options pin all of marp-core's raised defaults back to
// Marpit semantics — DeckViewer and the print contract are built on a plain
// <section> stream: inlineSVG off, breaks/linkify off, headings produce no
// ids (duplicate-id audit), no browser helper <script> injected; fence
// highlighting is handed back to markdown-it's default form, and
// postProcessSlide uniformly runs the site's shiki (the built-in hljs class
// shape cannot feed the highlight-bridging regex).
//
// Dual instances: the math-enabled instance produces HTML; with math on,
// marp-core appends the full KaTeX CSS (@font-face pointing at the jsDelivr
// CDN) to the rendered css, while the page-level /katex.min.css is already
// injected per needsKatex — the deck css neither needs nor should double-carry
// it. Since css is content-independent, a math:false twin instance renders
// empty to extract the pure theme css. The factory keeps the two instances'
// configs from drifting.
function createMarp(math: boolean, html: boolean): Marp {
  const marp = new Marp({
    inlineSVG: false,
    looseYAML: false,
    cssContainerQuery: false,
    emoji: { shortcode: true, unicode: false },
    math: math ? "katex" : false,
    script: false,
    slug: false,
    markdown: {
      html,
      breaks: false,
      linkify: false,
      highlight: () => "",
    },
  });
  marp.use(deckCallouts);
  marp.use(mark);
  marp.use(tasklist);
  marp.use(markdownItDeflist);
  marp.themeSet.default = marp.themeSet.add(deckThemeCss);
  return marp;
}

/** Instance cache (all four math × html combinations built lazily): the math
 *  instance produces HTML; the math:false twin extracts pure theme css. */
const marpCache = new Map<string, Marp>();

function getMarp(math: boolean, html: boolean): Marp {
  const key = `${math ? 1 : 0}${html ? 1 : 0}`;
  let marp = marpCache.get(key);
  if (!marp) {
    marp = createMarp(math, html);
    marpCache.set(key, marp);
  }
  return marp;
}

/** Inject intrinsic dimensions for site-local images (src starting with "/" →
 *  files under public/). Decks don't go through rehypeLocalImageSize's hast
 *  pipeline, so this is the string-level equivalent; the <img> attribute shape
 *  markdown-it produces is predictable (double quotes, no dimensions). */
function injectLocalImageSizes(html: string): string {
  return html.replace(/<img\b[^>]*>/g, (tag) => {
    const src = /src="([^"]+)"/.exec(tag)?.[1] ?? "";
    if (!src.startsWith("/")) {
      return tag;
    }
    let out = /\balt=/.test(tag) ? tag : tag.replace(/>$/, ' alt="">');
    try {
      const dim = imageSize(readFileSync(join(process.cwd(), "public", src)));
      out = out.replace(/\bsrc="[^"]*"/, (match) => `${match} width="${dim.width}" height="${dim.height}"`);
    } catch {
      // No matching file under public/ (off-site images etc.); don't inject dimensions
    }
    return out;
  });
}

/** Per-slide post-processing: heading demotion → code re-highlight / mermaid
 *  placeholders → image dimensions → strip id, add data-slide → inject
 *  presenter notes. The three site seams take effect via options. */
function postProcessSlide(
  page: string,
  index: number,
  notes: readonly string[],
  options: Omit<Required<DeckCompileOptions>, "highlight"> & { highlight?: (lang: string, code: string) => string },
): string {
  let html = page;
  if (options.demoteHeadings) {
    // The page h1 belongs to the post title; slide titles start at h2
    html = html.replace(
      /<(\/?)h([1-5])(?=[\s>])/g,
      (_match, slash: string, level: string) => `<${slash}h${Number(level) + 1}`,
    );
  }
  html = html.replace(
    /<pre><code(?: class="language-([\w#+.-]+)")?>([\s\S]*?)<\/code><\/pre>/g,
    (match, lang: string | undefined, code: string) => {
      const decoded = decodeEntities(code);
      // mermaid uses the site's usual placeholder container: DeckViewer
      // mounts MermaidRenderer for lazy rendering, and the print light-theme
      // coordination applies automatically (syntax matches the article
      // vocabulary)
      if (lang === "mermaid") {
        return `<div class="mermaid-placeholder" data-chart="${escapeAttr(decoded)}"></div>`;
      }
      // Typora sequence/flow: translated to mermaid at build time (same conversion as the article pipeline)
      if (lang === "sequence" || lang === "flow") {
        const chart = lang === "sequence" ? translateSequenceToMermaid(decoded) : translateFlowToMermaid(decoded);
        return `<div class="mermaid-placeholder" data-chart="${escapeAttr(chart)}"></div>`;
      }
      return options.highlight ? options.highlight(lang ?? "", decoded) : match;
    },
  );
  if (options.imageSizes) {
    html = injectLocalImageSizes(html);
  }
  // Task list checkboxes are purely decorative; add aria-hidden (same as the article pipeline's compileMarkdown)
  html = html.replace(/<input((?:(?!aria-hidden)[^>]*)?type="checkbox"[^>]*)>/g, '<input aria-hidden="true"$1>');
  html = html.replace(/^<section\b([^>]*)>/, (_match, attrs: string) => {
    const cleaned = attrs.replace(/\s+id="[^"]*"/g, "");
    return `<section data-slide="${index + 1}"${cleaned}>`;
  });
  // Wrap the body in .deck-body: the player's overflow fitting (deckFit) does
  // proportional scaling + width compensation on it — on the fixed 720px
  // canvas an over-tall page shrinks whole to fit inside the canvas instead
  // of being clipped by overflow. The notes aside sits outside the wrapper
  // (its injection happens after this).
  html = html.replace(
    /^(<section\b[^>]*>)([\s\S]*)<\/section>\s*$/,
    (_match, open: string, inner: string) => `${open}<div class="deck-body">${inner}</div></section>`,
  );
  if (notes.length > 0) {
    const body = notes.map((note) => `<p>${escapeHtml(note)}</p>`).join("");
    html = html.replace(/<\/section>\s*$/, `<aside class="deck-notes">${body}</aside></section>`);
  }
  return html;
}

/** Markdown (Marpit dialect) → per-slide HTML + theme CSS. Render errors are
 *  thrown to fail the build (fail-closed, consistent with the site pipeline's
 *  trust model); default options = blog behavior. */
export function compileDeck(markdown: string, options: DeckCompileOptions = {}): DeckResult {
  const resolved: Omit<Required<DeckCompileOptions>, "highlight"> & {
    highlight?: (lang: string, code: string) => string;
  } = {
    html: options.html ?? true,
    // Blog default = the site's shiki dual themes (the zjsearch twin file has
    // no such import; its default keeps markdown-it's default form — the site
    // seam lives in each caller's own default)
    highlight: options.highlight ?? highlightCode,
    imageSizes: options.imageSizes ?? true,
    demoteHeadings: options.demoteHeadings ?? true,
  };
  // gray-matter's content begins with a newline, while marpit's front-matter
  // plugin requires the directive block at character 0 of the document —
  // leading whitespace makes the directive block fail to parse and `---` gets
  // rendered as markdown (observed: empty slides + the directive paragraph
  // underlined into a heading)
  const source = markdown.replace(/^\s+/, "");
  const marp = getMarp(true, resolved.html);
  const { html: pages, comments } = marp.render(source, { htmlAsArray: true });
  const { css } = getMarp(false, resolved.html).render("");
  const list = Array.isArray(pages) ? pages : [pages];
  const slides = list.map((page, index) => postProcessSlide(page, index, comments[index] ?? [], resolved));
  return { slides, css, count: slides.length };
}

/** Placeholder structure for the embed form (```marp fence): styles + slides
 *  travel through contentHtml's single-source DOM channel; DeckViewer
 *  extracts from .deck-embed and re-renders the enhanced version, and without
 *  JS this structure itself is a fully readable stacked view. @page must be
 *  stripped — otherwise a deck embedded in an article hijacks the paper size
 *  of the whole page when printing. */
export function renderDeckEmbed(result: DeckResult): string {
  const css = result.css.replace(/@page\s*\{[^}]*\}\s*/g, "");
  return `<div class="deck-embed"><style data-deck-css>${css}</style><div class="marpit deck-embed-body" data-deck-content>${result.slides.join("\n")}</div></div>`;
}
