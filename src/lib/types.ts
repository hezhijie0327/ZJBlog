// Page payload (discriminated union): generated at build time by tools/payloads.ts,
// embedded in each page's HTML as
// <script id="page-data" type="application/json">; during client-side navigation the
// same script is extracted from the target page's HTML. globals.page is the discriminant;
// dispatch lives in src/app.tsx.

import type { ComponentType } from "react";

export type PageKind =
  | "home"
  | "blogs"
  | "blog-post"
  | "blog-tag"
  | "travels"
  | "travel"
  | "projects"
  | "project"
  | "archives"
  | "support"
  | "og"
  | "not-found";

/** Table-of-contents entry (extracted at build time; id = rehype-slug anchor). */
export interface TocItem {
  id: string;
  text: string;
  depth: 2 | 3;
}

/** Slide deck metadata (blog posts with frontmatter deck: true). css travels with the
 *  payload: <head> does not change on SPA client-side navigation (the router only swaps
 *  title/description), so styles must be injectable after navigation; the slide HTML
 *  itself follows the contentHtml single-copy-in-DOM contract (data-deck-content), and
 *  the slide count is derived from the HTML at player runtime. */
export interface DeckMeta {
  /** Theme styles generated by marpit (scoped to div.marpit > section) */
  css: string;
}

/** User-coordinate canvas size of the travel map: shared by tools/travelMap.ts's viewBox
 *  and the client-side controller (coordinate conversion for TravelsPage zoom/pan) so the
 *  two cannot drift apart. */
export const TRAVEL_MAP_SIZE = { w: 1280, h: 484 } as const;

export interface PageGlobals {
  page: PageKind;
  /** UI locale tag (matches the wordbook file names under src/lib/i18n/) */
  locale: "zh-CN";
  siteName: string;
  siteUrl: string;
  /** Full <title> text (including the " | site name" suffix), written to document.title on client-side navigation */
  title: string;
  description: string;
  /** Extra OpenGraph fields for post pages */
  og?: { type: "article"; publishedTime?: string; tags?: string[] };
}

/** Encrypted post envelope: produced at build time by tools/crypto.ts (Argon2id-derived
 *  key + AES-256-GCM encryption; the plaintext is JSON { html, toc }), decrypted
 *  client-side by src/lib/locked.ts using the parameters inside the envelope. Both sides
 *  share this contract; parameter evolution branches on v. */
export interface LockedContent {
  /** Envelope version */
  v: 1;
  /** Argon2id: memory (KiB) / iterations / parallelism / derived key bytes */
  m: number;
  t: number;
  p: number;
  len: number;
  /** base64: 16B random salt (unique per post per build; regenerated on every rebuild) */
  salt: string;
  /** base64: 12B random IV */
  iv: string;
  /** base64: AES-256-GCM ciphertext (auth tag appended, i.e. WebCrypto's native format) */
  ciphertext: string;
}

export interface BlogListItem {
  slug: string;
  title: string;
  date?: string;
  description?: string;
  category?: string;
  tags: string[];
  /** Reading time in minutes; display copy comes from i18n (meta.readingTime) */
  readingMinutes: number;
  /** Encrypted post: the list only exposes title-level metadata (description is a content excerpt and never public); the body needs a password to unlock */
  locked?: boolean;
  /** Full slide deck (frontmatter deck: true); the list renders a badge */
  deck?: true;
}

export interface ProjectListItem {
  slug: string;
  title: string;
  date?: string;
  description?: string;
  type: "personal" | "starred";
  tags: string[];
  link?: string;
  /** Cover image (frontmatter.image); when absent the page renders no cover slot */
  image?: string;
}

export interface HomeData {
  globals: PageGlobals & { page: "home" };
  projects: ProjectListItem[];
  blogs: BlogListItem[];
  /** Home travel section: the same list as /travels/ (without the map SVG) */
  trips: TravelListItem[];
}

export interface BlogsData {
  globals: PageGlobals & { page: "blogs" };
  blogs: BlogListItem[];
}

export interface BlogPostData {
  globals: PageGlobals & { page: "blog-post" };
  /** contentHtml does not go into the page-data script (long posts would double the
   *  document size): the body lives as a single copy in the DOM and only exists after the
   *  boot pipeline (first frame) or the navigation pipeline (fetch + parse) injects it.
   *  Note locked is a boolean flag on list items but a ciphertext envelope here; deck is a
   *  boolean flag on list items but { css } metadata here — both are Omit'ed and redefined. */
  post: Omit<BlogListItem, "locked" | "deck"> & {
    toc: TocItem[];
    contentHtml?: string;
    /** Body contains KaTeX formulas: the page must load katex.min.css (SSR injection / Prose top-up) */
    needsKatex?: boolean;
    /** Hand-written summary (frontmatter.summary; the summary card renders only when present) */
    summary?: string;
    /** Encryption envelope (set = locked post): contentHtml/toc/summary are absent from
     *  the payload; after the lock screen unlocks, the client decrypts and restores the body */
    locked?: LockedContent;
    /** Slide deck metadata (set = full deck; DeckViewer replaces Prose) */
    deck?: DeckMeta;
    /** Older / newer post on the timeline (computed at build time; undefined at the edges) */
    prev?: PostNavLink;
    next?: PostNavLink;
  };
}

/** Previous / next navigation links */
export interface PostNavLink {
  slug: string;
  title: string;
}

/** Search index entry (/search-index.json; produced at build time by generators.ts,
 *  consumed by the command palette — both sides share this contract to prevent field
 *  drift). */
export interface SearchItem {
  title: string;
  description?: string;
  type: "blog" | "project";
  tags: string[];
  href: string;
}

export interface BlogTagData {
  globals: PageGlobals & { page: "blog-tag" };
  /** Tag name (decoded original) */
  tag: string;
  blogs: BlogListItem[];
}

/** Travel entry (shared by the /travels/ postcard wall and the map pins). Pins and
 *  place/date form the public memorial layer; travels matching secret get their details
 *  locked, and content fields like summary/cover never leave the site. */
export interface TravelListItem {
  slug: string;
  title: string;
  /** Short label on the map pin */
  place: string;
  /** [lng, lat] (GeoJSON convention) */
  coords: [number, number];
  date?: string;
  endDate?: string;
  /** Companion: couple renders a heart pin / solo renders a ring pin */
  companion: "couple" | "solo";
  /** Cover image (postcard card; never shipped for locked posts) */
  cover?: string;
  summary?: string;
  /** Related blog post (/blogs/...) */
  link?: string;
  /** Details are locked (frontmatter.secret matched) */
  locked?: boolean;
}

export interface TravelsData {
  globals: PageGlobals & { page: "travels" };
  trips: TravelListItem[];
  /** World map SVG baked at build time (including the city detail layer and the replay
   *  camera choreography data-stops): stored as a single copy in the DOM (#travel-map) and
   *  only present after the boot or navigation pipeline injects it (same contract as
   *  contentHtml; excluded from page-data) */
  mapSvg?: string;
}

export interface TravelData {
  globals: PageGlobals & { page: "travel" };
  /** Same as BlogPostData: contentHtml is injected from the DOM, not carried in page-data.
   *  locked is a boolean flag on list items but a ciphertext envelope here, hence Omit'ed
   *  and redefined. */
  trip: Omit<TravelListItem, "locked"> & {
    contentHtml?: string;
    needsKatex?: boolean;
    locked?: LockedContent;
  };
}

export interface ProjectsData {
  globals: PageGlobals & { page: "projects" };
  projects: ProjectListItem[];
}

export interface ProjectData {
  globals: PageGlobals & { page: "project" };
  /** Same as BlogPostData: contentHtml is injected from the DOM, not carried in page-data */
  project: ProjectListItem & { contentHtml?: string; needsKatex?: boolean };
}

export interface ArchivesData {
  globals: PageGlobals & { page: "archives" };
  blogs: BlogListItem[];
}

export interface SupportData {
  globals: PageGlobals & { page: "support" };
}

/** OG share-card page (/og/, noindex utility page): a fixed 1200×630 canvas for a headless
 *  browser to screenshot into public/og-default.png. Content comes from the site config and
 *  the Chinese copy baseline and does not follow the UI language (the screenshot language
 *  must be stable). */
export interface OgData {
  globals: PageGlobals & { page: "og" };
}

export interface NotFoundData {
  globals: PageGlobals & { page: "not-found" };
}

export type AnyPageData =
  | HomeData
  | BlogsData
  | BlogPostData
  | BlogTagData
  | TravelsData
  | TravelData
  | ProjectsData
  | ProjectData
  | ArchivesData
  | SupportData
  | OgData
  | NotFoundData;

// Type guards (the nested discriminant field cannot be narrowed with a direct switch)
export function isHomeData(data: AnyPageData): data is HomeData {
  return data.globals.page === "home";
}
export function isBlogsData(data: AnyPageData): data is BlogsData {
  return data.globals.page === "blogs";
}
export function isBlogPostData(data: AnyPageData): data is BlogPostData {
  return data.globals.page === "blog-post";
}
export function isBlogTagData(data: AnyPageData): data is BlogTagData {
  return data.globals.page === "blog-tag";
}
export function isTravelsData(data: AnyPageData): data is TravelsData {
  return data.globals.page === "travels";
}
export function isTravelData(data: AnyPageData): data is TravelData {
  return data.globals.page === "travel";
}
export function isProjectsData(data: AnyPageData): data is ProjectsData {
  return data.globals.page === "projects";
}
export function isProjectData(data: AnyPageData): data is ProjectData {
  return data.globals.page === "project";
}
export function isArchivesData(data: AnyPageData): data is ArchivesData {
  return data.globals.page === "archives";
}
export function isSupportData(data: AnyPageData): data is SupportData {
  return data.globals.page === "support";
}
export function isOgData(data: AnyPageData): data is OgData {
  return data.globals.page === "og";
}

/** Sync page component table for SSR/prerender: renderToString cannot await React.lazy,
 *  so the server renders real content directly from this table (the client goes through
 *  pages/registry.ts chunking + Suspense). */
export interface SyncPages {
  home: ComponentType<{ data: HomeData }>;
  blogs: ComponentType<{ data: BlogsData }>;
  "blog-post": ComponentType<{ data: BlogPostData }>;
  "blog-tag": ComponentType<{ data: BlogTagData }>;
  travels: ComponentType<{ data: TravelsData }>;
  travel: ComponentType<{ data: TravelData }>;
  projects: ComponentType<{ data: ProjectsData }>;
  project: ComponentType<{ data: ProjectData }>;
  archives: ComponentType<{ data: ArchivesData }>;
  support: ComponentType;
  og: ComponentType;
}
